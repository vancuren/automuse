"""mediamtx config and process helpers, plus the ffmpeg HEVC publisher command.

mediamtx serves RTSP only, on 127.0.0.1, TCP transport only (so no UDP RTP/RTCP ports are
bound). Every other protocol (RTMP, HLS, WebRTC, SRT, MoQ) and every HTTP service (API, metrics,
pprof, playback) is disabled. tests/twin/test_media.py checks the listening sockets.
"""
from __future__ import annotations

import os
import shutil
import socket
import subprocess
import time
from pathlib import Path
from typing import Optional

RTSP_PATH = "live/ch00_1"


def mediamtx_config(rtsp_port: int, host: str = "127.0.0.1", path: str = RTSP_PATH) -> str:
    """YAML text for a loopback, RTSP-only mediamtx."""
    return f"""# Generated by mhd.twin.media: RTSP only, loopback only, TCP only.
logLevel: warn
logDestinations: [stdout]
readTimeout: 10s
writeTimeout: 10s
api: false
metrics: false
pprof: false
playback: false
rtsp: true
rtspTransports: [tcp]
rtspEncryption: "no"
rtspAddress: {host}:{rtsp_port}
rtmp: false
hls: false
webrtc: false
srt: false
moq: false
paths:
  {path}:
    source: publisher
"""


def write_mediamtx_config(out_dir: Path, rtsp_port: int) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / f"mediamtx_{rtsp_port}.yml"
    p.write_text(mediamtx_config(rtsp_port), encoding="utf-8")
    return p


def mediamtx_binary() -> Path:
    tools = os.environ.get("MHD_TOOLS")
    if tools:
        cand = Path(tools) / "mediamtx" / "mediamtx"
        if cand.exists():
            return cand
    raise FileNotFoundError("mediamtx not found under $MHD_TOOLS/mediamtx (source env.sh)")


def port_open(port: int, host: str = "127.0.0.1", timeout: float = 0.2) -> bool:
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


def start_mediamtx(rtsp_port: int, log_dir: Path, wait_s: float = 5.0) -> subprocess.Popen:
    if port_open(rtsp_port):
        raise RuntimeError(f"port {rtsp_port} is already in use; is another mediamtx running?")
    cfg = write_mediamtx_config(log_dir, rtsp_port)
    log = open(log_dir / f"mediamtx_{rtsp_port}.log", "ab")
    proc = subprocess.Popen([str(mediamtx_binary()), str(cfg)], stdout=log, stderr=subprocess.STDOUT,
                            cwd=str(log_dir))
    deadline = time.monotonic() + wait_s
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            raise RuntimeError(f"mediamtx exited with {proc.returncode}; see {log.name}")
        if port_open(rtsp_port):
            return proc
        time.sleep(0.05)
    proc.terminate()
    raise RuntimeError("mediamtx did not start listening in time")


def ffmpeg_binary() -> str:
    path = shutil.which("ffmpeg")
    if not path:
        raise FileNotFoundError("ffmpeg not on PATH")
    return path


def ffmpeg_publish_cmd(url: str, width: int = 1280, height: int = 720, fps: int = 25,
                       bitrate: str = "3M", gop: int = 25) -> list[str]:
    """Raw BGR frames on stdin -> hevc_videotoolbox -> RTSP (TCP) publish.

    Matches the drone's stream shape as far as known: HEVC 1280x720, no B-frames, 1 s GOP.
    Wall-clock input timestamps keep stalls and bursts visible to the receiver.
    """
    return [
        ffmpeg_binary(), "-hide_banner", "-loglevel", "warning", "-nostats",
        "-fflags", "nobuffer",
        "-f", "rawvideo", "-pix_fmt", "bgr24", "-s", f"{width}x{height}", "-framerate", str(fps),
        "-use_wallclock_as_timestamps", "1",
        "-i", "pipe:0",
        "-an", "-fps_mode", "passthrough",          # one output frame per input frame, never duplicated
        "-c:v", "hevc_videotoolbox", "-b:v", bitrate, "-bf", "0", "-g", str(gop), "-realtime", "1",
        "-profile:v", "main", "-pix_fmt", "nv12",
        "-flush_packets", "1", "-muxdelay", "0", "-max_delay", "0",
        "-f", "rtsp", "-rtsp_transport", "tcp", url,
    ]


def ffmpeg_file_cmd(out_path: Path, width: int, height: int, fps: int = 25, bitrate: str = "6M") -> list[str]:
    """Raw BGR frames on stdin -> HEVC MP4 file (used for the chase-view recording)."""
    return [
        ffmpeg_binary(), "-hide_banner", "-loglevel", "warning", "-nostats", "-y",
        "-f", "rawvideo", "-pix_fmt", "bgr24", "-s", f"{width}x{height}", "-framerate", str(fps),
        "-i", "pipe:0", "-an",
        "-c:v", "hevc_videotoolbox", "-b:v", bitrate, "-tag:v", "hvc1", "-pix_fmt", "nv12",
        "-movflags", "+faststart", str(out_path),
    ]


def stop_process(proc: Optional[subprocess.Popen], timeout: float = 3.0) -> None:
    if proc is None or proc.poll() is not None:
        return
    try:
        if proc.stdin:
            try:
                proc.stdin.close()
            except Exception:
                pass
        proc.terminate()
        proc.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait(timeout=timeout)
